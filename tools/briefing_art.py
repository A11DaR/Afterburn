def render(output):
    indices = decompress(b85decode(b"".join(PIXELS.split())))
    if len(indices) != SIZE[0] * SIZE[1] or sha256(PALETTE + indices).hexdigest() != PIXEL_DIGEST:
        raise ValueError("Damaged title artwork")
    artwork = Image.frombytes("P", SIZE, indices)
    artwork.putpalette(PALETTE)
    output.parent.mkdir(parents=True, exist_ok=True)
    artwork.save(output, format="PNG", optimize=True)


